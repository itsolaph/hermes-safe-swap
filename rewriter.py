"""Turn a shell command into its reversible twin, or return ``None`` to leave it alone."""

from __future__ import annotations

import re
from dataclasses import dataclass

from .config import Config, quarantine_expr
from .destructive import argv_destructive, text_destructive
from .rules import Edit, Skip, apply_rules
from .shellgen import MARKER
from .shellscan import Bail, Simple, scan

__all__ = ["MAX_COMMAND_LEN", "Analysis", "Rewrite", "analyze", "extract_receipt_id", "rewrite"]

MAX_COMMAND_LEN = 100_000
_HINT = re.compile(r"\b(rm|git)\b")
_SHELLS = {"bash", "sh", "dash", "zsh", "ksh", "fish"}
_OPAQUE = {"eval", "xargs", "source", ".", "parallel"}
_FIND_EXEC = {"-exec", "-execdir", "-ok", "-okdir", "-delete"}
SCRIPT_MARKER = "SS_B="  # first word of every script generated by undo.py
_MARKER_ID = re.compile(re.escape(MARKER) + r"([0-9a-f]{6})\b")


@dataclass(frozen=True)
class Rewrite:
    command: str
    kinds: tuple[str, ...]
    original: str


def extract_receipt_id(command: object) -> str | None:
    """The receipt id embedded in an already-rewritten command, if any."""
    if not isinstance(command, str):
        return None
    m = _MARKER_ID.search(command)
    return m.group(1) if m else None


def _opaque(seg: Simple) -> bool:
    if not seg.argv:
        return False
    name = seg.argv[0].val.rsplit("/", 1)[-1]
    args = [t.val for t in seg.argv[1:]]
    if name in _OPAQUE:
        return True
    if name in _SHELLS:
        return any(a.startswith("-") and not a.startswith("--") and "c" in a for a in args)
    return name == "find" and any(a in _FIND_EXEC for a in args)


@dataclass(frozen=True)
class Analysis:
    """What the rewriter decided: the swap (if any) and why destructive-looking parts were left alone."""

    rewrite: Rewrite | None = None
    skips: tuple[str, ...] = ()


_NOTHING = Analysis()


def _opaque_reason(seg: Simple) -> str:
    name = seg.argv[0].val.rsplit("/", 1)[-1]
    if name in _SHELLS:
        return f"{name} -c command string"
    return "find -exec/-delete" if name == "find" else f"{name} wrapper"


def analyze(command: object, cfg: Config, rid: str) -> Analysis:
    """Decide what to do with *command*; never raises for any input (see :func:`rewrite`).

    ``skips`` lists, in order and without duplicates, the reasons why a command that really looks
    destructive (``rm -r``, ``git reset --hard`` ...) was left untouched. It is empty for harmless
    commands, for already-rewritten ones and for exclusions the user configured.
    """
    if not isinstance(command, str) or not command:
        return _NOTHING
    if MARKER in command or not _HINT.search(command):
        return _NOTHING
    if command.lstrip().startswith(SCRIPT_MARKER):  # safe-swap's own /unswap and purge scripts (see undo.py)
        return _NOTHING
    if len(command) > MAX_COMMAND_LEN:
        return Analysis(None, ("command too long",)) if text_destructive(command[:MAX_COMMAND_LEN]) else _NOTHING
    try:
        segments = scan(command)
    except Bail as exc:
        return Analysis(None, (f"unsupported syntax: {exc}",)) if text_destructive(command) else _NOTHING
    opaque = [s for s in segments if _opaque(s)]
    if opaque:
        looks = any(argv_destructive([t.val for t in s.argv]) for s in segments)
        return Analysis(None, (_opaque_reason(opaque[0]),)) if looks else _NOTHING
    base = quarantine_expr(cfg.quarantine_dir)
    edits: list[Edit] = []
    skips: list[str] = []
    for seg in segments:
        slot = rid if not edits else f"{rid}.{len(edits)}"
        result = apply_rules(command, seg, cfg, base, rid, slot)
        if isinstance(result, Edit):
            edits.append(result)
        elif isinstance(result, Skip):
            skips.append(result.reason)
    reasons = tuple(dict.fromkeys(skips))
    if not edits:
        return Analysis(None, reasons)
    out = command
    for e in sorted(edits, key=lambda e: e.start, reverse=True):
        out = out[: e.start] + e.text + out[e.end :]
    kinds = tuple(dict.fromkeys(e.kind for e in edits))
    return Analysis(Rewrite(out, kinds, command), reasons)


def rewrite(command: object, cfg: Config, rid: str) -> Rewrite | None:
    """Return the reversible twin of *command*, or ``None`` (run it untouched).

    Never raises for any input: unexpected types, oversized or unparseable commands, and
    already-rewritten commands (carrying :data:`MARKER`) all yield ``None``.
    """
    return analyze(command, cfg, rid).rewrite
